def step(doc, n, text):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.first_line_indent = Pt(-24)
    pf.left_indent = Pt(24)
    pf.line_spacing = 1.5
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    _run_cn(p, '%d. %s' % (n, text), size=12)
    return p


def steps(doc, items):
    for i, t in enumerate(items, 1):
        step(doc, i, t)


